// Asset loading with runtime detection: real files are used as soon as they exist, otherwise the
// caller falls back to procedural stand-ins behind the same interface.
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { MeshoptDecoder } from 'three/addons/libs/meshopt_decoder.module.js';
import { ASSET_BASE } from '../config.js';

export const loadingManager = new THREE.LoadingManager();
const gltfLoader = new GLTFLoader(loadingManager).setMeshoptDecoder(MeshoptDecoder);

const progress = { weights: new Map(), listeners: new Set() };
/** Progress reporting: each task declares a weight and reports 0..1. */
export function reportProgress(task, value, weight = 1) {
  progress.weights.set(task, { value, weight });
  let total = 0;
  let done = 0;
  for (const { value: v, weight: w } of progress.weights.values()) {
    total += w;
    done += v * w;
  }
  for (const fn of progress.listeners) fn(total ? done / total : 0, task);
}
export const onProgress = (fn) => progress.listeners.add(fn);

// Asset index (assets/index.json: generated by the Vite plugin in dev and at build time). When it is
// available, missing files are never requested (no 404 noise); otherwise we probe each file.
let indexPromise = null;
function assetIndex() {
  if (!indexPromise) {
    indexPromise = fetch(ASSET_BASE + 'index.json', { cache: 'no-cache' })
      .then((r) => (r.ok && !(r.headers.get('content-type') || '').includes('text/html') ? r.json() : null))
      .then((j) => (j && Array.isArray(j.files) ? new Set(j.files) : null))
      .catch(() => null);
  }
  return indexPromise;
}
/** false when the index says the file is absent, true when present, null when unknown. */
export async function listed(path) {
  const idx = await assetIndex();
  return idx ? idx.has(path) : null;
}

/** Fetch JSON, or null when missing / not JSON (dev server or prod fallback page). */
export async function fetchJSON(path) {
  if ((await listed(path)) === false) return null;
  try {
    const res = await fetch(ASSET_BASE + path, { cache: 'no-cache' });
    if (!res.ok) return null;
    const type = res.headers.get('content-type') || '';
    if (type.includes('text/html')) return null;
    return await res.json();
  } catch {
    return null;
  }
}

/** True when a binary glTF exists at path (HEAD-like check that tolerates servers without HEAD). */
export async function assetExists(path) {
  const known = await listed(path);
  if (known !== null) return known;
  try {
    const res = await fetch(ASSET_BASE + path, { method: 'HEAD', cache: 'no-cache' });
    if (!res.ok) return false;
    const type = res.headers.get('content-type') || '';
    return !type.includes('text/html');
  } catch {
    return false;
  }
}

/** Load a GLB; resolves null on failure (missing file, bad data). */
export async function loadGLB(path, task) {
  if ((await listed(path)) === false) {
    if (task) reportProgress(task, 1);
    return null;
  }
  return new Promise((resolve) => {
    gltfLoader.load(
      ASSET_BASE + path,
      (gltf) => {
        if (task) reportProgress(task, 1);
        resolve(gltf);
      },
      (ev) => {
        if (task && ev.total) reportProgress(task, ev.loaded / ev.total);
      },
      (err) => {
        console.warn(`[assets] ${path} indisponible :`, err?.message || err);
        if (task) reportProgress(task, 1);
        resolve(null);
      },
    );
  });
}
